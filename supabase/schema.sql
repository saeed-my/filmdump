-- filmdump schema. Run once in the Supabase SQL editor.
-- The migrations in supabase/migrations add security fixes and rate limits
-- on top of this; with the CLI, `supabase db push` applies all of them.

create table public.films (
  id bigint generated by default as identity primary key,
  owner uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title text not null,
  rating numeric(3, 1) not null check (rating >= 0 and rating <= 10),
  poster text not null default '',
  watched_date date,
  notes text not null default '',
  recommended boolean not null default false,
  recommend_note text not null default '',
  created_at timestamptz not null default now()
);

alter table public.films enable row level security;

-- Only the signed-in owner can read or change their log.
create policy "owner reads films" on public.films
  for select to authenticated using (auth.uid() = owner);
create policy "owner adds films" on public.films
  for insert to authenticated with check (auth.uid() = owner);
create policy "owner edits films" on public.films
  for update to authenticated using (auth.uid() = owner) with check (auth.uid() = owner);
create policy "owner deletes films" on public.films
  for delete to authenticated using (auth.uid() = owner);

grant select, insert, update, delete on public.films to authenticated;
revoke all on public.films from anon;

-- The public page reads this view. It exposes recommended films only,
-- and leaves out private notes and watch dates.
create view public.recommendations as
  select id, title, rating, poster, recommend_note
  from public.films
  where recommended;

grant select on public.recommendations to anon, authenticated;

-- Sending one film to one friend. Each friend gets a private link,
-- /f/<token>. Friends never sign in: the token is who they are.
-- Run this block once more if you set up sharing before it existed.

create table public.friends (
  id bigint generated by default as identity primary key,
  owner uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 60),
  token text not null unique check (token ~ '^[0-9a-f]{32}$'),
  created_at timestamptz not null default now()
);

create table public.sends (
  id bigint generated by default as identity primary key,
  owner uuid not null default auth.uid() references auth.users (id) on delete cascade,
  friend_id bigint not null references public.friends (id) on delete cascade,
  film_id bigint not null references public.films (id) on delete cascade,
  note text not null default '' check (length(note) <= 280),
  status text not null default 'pending'
    check (status in ('pending', 'watched', 'seen', 'pass')),
  friend_rating numeric(3, 1) check (friend_rating >= 0 and friend_rating <= 10),
  friend_line text not null default '' check (length(friend_line) <= 280),
  responded_at timestamptz,
  -- Cleared whenever the friend answers, set when the owner opens the film.
  seen_at timestamptz,
  created_at timestamptz not null default now(),
  unique (friend_id, film_id),
  check (status <> 'watched' or friend_rating is not null),
  check (status <> 'pass' or friend_rating is null)
);

alter table public.friends enable row level security;
alter table public.sends enable row level security;

create policy "owner manages friends" on public.friends
  for all to authenticated using (auth.uid() = owner) with check (auth.uid() = owner);
create policy "owner manages sends" on public.sends
  for all to authenticated using (auth.uid() = owner) with check (auth.uid() = owner);

grant select, insert, update, delete on public.friends, public.sends to authenticated;
revoke all on public.friends, public.sends from anon;

-- A friend's page: their name and the films sent to them, newest first.
-- Returns null for an unknown token. Never exposes notes or watch dates.
create function public.get_friend_page(p_token text)
returns json
language sql stable security definer set search_path = public
as $$
  select json_build_object(
    'name', f.name,
    'picks', coalesce((
      select json_agg(json_build_object(
        'id', s.id,
        'title', m.title,
        'poster', m.poster,
        'rating', m.rating,
        'note', s.note,
        'status', s.status,
        'friend_rating', s.friend_rating,
        'friend_line', s.friend_line
      ) order by s.created_at desc)
      from public.sends s
      join public.films m on m.id = s.film_id
      where s.friend_id = f.id
    ), '[]'::json)
  )
  from public.friends f
  where f.token = p_token;
$$;

-- A friend answers one pick. The table's checks enforce the score rules.
create function public.respond_to_send(
  p_token text, p_send_id bigint, p_status text, p_rating numeric, p_line text
)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if p_status not in ('watched', 'seen', 'pass') then
    raise exception 'invalid status';
  end if;
  update public.sends s
  set status = p_status,
      friend_rating = p_rating,
      friend_line = coalesce(trim(p_line), ''),
      responded_at = now(),
      seen_at = null
  from public.friends f
  where s.id = p_send_id and s.friend_id = f.id and f.token = p_token;
  if not found then
    raise exception 'pick not found';
  end if;
end;
$$;

revoke execute on function public.get_friend_page(text) from public;
revoke execute on function public.respond_to_send(text, bigint, text, numeric, text) from public;
grant execute on function public.get_friend_page(text) to anon, authenticated;
grant execute on function public.respond_to_send(text, bigint, text, numeric, text) to anon, authenticated;
